def pearson(a,b):
    x=[v for r in a['strategy_weights'] for v in r]; y=[v for r in b['strategy_weights'] for v in r]
    mx=sum(x)/len(x); my=sum(y)/len(y)
    n=sum((u-mx)*(v-my) for u,v in zip(x,y)); d=(sum((u-mx)**2 for u in x)*sum((v-my)**2 for v in y))**.5
    return round(n/d,6) if d else None

