def parse(text, width):
    rows = []
    for line in text.strip().splitlines():
        nums, refs, reason = line.split('|')
        values = [Decimal(n) for n in nums.split()]
        assert len(values) == width and all(0 <= n <= 1 for n in values)
        if width == 5:
            assert sum(values) == Decimal(1), line
        rows.append(([float(n) for n in values], [] if refs == '-' else [int(r) for r in refs.split(',')], reason))
    return rows


def signature(major):
    return tuple(row.index(max(row)) for row in major['strategy_weights'])


def audit(catalog, targets):
    active = {m['id']: m for m in catalog if m.get('motive_driven') is not False}
    assert len(active) == 202
    sig = {mid: signature(m) for mid,m in active.items()}
    collisions = [(a,b) for a,b in itertools.combinations(sig,2) if sig[a] == sig[b]]
    assert not collisions, f'25/25 signature collision: {collisions}'
    neighbors = {}
    for mid in targets:
        neighbors[mid] = sorted([{'id': other, 'agree': sum(a == b for a,b in zip(sig[mid], sig[other]))}
                                  for other in sig if other != mid], key=lambda r: (-r['agree'],r['id']))[:5]
    suspicious = [(a,b,sum(x == y for x,y in zip(sig[a],sig[b])))
                  for a,b in itertools.combinations(sig,2) if a in targets or b in targets]
    return {'active_count':len(active), 'collisions':collisions,
            'statistical_top5_not_semantic_neighbors':neighbors,
            'pairs_20_24': [x for x in suspicious if 20 <= x[2] <= 24]}


