def pearson(a,b):
    aa=[x for row in a for x in row]; bb=[x for row in b for x in row]
    am=sum(aa)/len(aa); bm=sum(bb)/len(bb)
    numerator=sum((x-am)*(y-bm) for x,y in zip(aa,bb))
    denom=math.sqrt(sum((x-am)**2 for x in aa)*sum((y-bm)**2 for y in bb))
    return numerator/denom if denom else None


