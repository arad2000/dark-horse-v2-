def to_row(raw):
    """Four-decimal normalization; residual belongs to largest RAW component."""
    raw=[Decimal(str(n)) for n in raw]
    assert len(raw)==5 and all(Decimal(0)<=n<=Decimal(1) for n in raw) and sum(raw)>0
    total=sum(raw)
    row=[(n/total).quantize(Decimal('.0001'),rounding=ROUND_HALF_UP) for n in raw]
    row[max(range(5),key=lambda i:raw[i])] += Decimal(1)-sum(row)
    assert sum(row)==1 and all(0<=n<=1 for n in row)
    return [float(n) for n in row]


def parse(text,width):
    result=[]
    for line in text.strip().splitlines():
        a,b,reason=line.split('|')
        raw=[Decimal(n) for n in a.split()]
        assert len(raw)==width and all(0<=n<=1 for n in raw) and reason
        refs=[] if b=='-' else [int(r) for r in b.split(',')]
        assert len(refs)==len(set(refs)) and set(refs)<=set(range(1,8))
        row=to_row(raw) if width==5 else [float(n) for n in raw]
        assert len(set(row))==1 or refs, 'Slope without witness'
        result.append({'raw':[str(n) for n in raw],'row':row,'refs':refs,'reason':reason})
    assert len(result)==(25 if width==5 else 15)
    return result


def signature(m):
    return tuple(row.index(max(row)) for row in m['strategy_weights'])


def global_audit(catalog,targets):
    active={m['id']:m for m in catalog if m.get('motive_driven') is not False}
    assert len(active)==202
    sig={mid:signature(m) for mid,m in active.items()}
    collisions=[(a,b) for a,b in itertools.combinations(sig,2) if sig[a]==sig[b]]
    assert not collisions, f'25/25 collision: {collisions}'
    pairs=[{'a':a,'b':b,'agree':sum(x==y for x,y in zip(sig[a],sig[b]))}
           for a,b in itertools.combinations(sig,2) if a in targets or b in targets]
    top={mid:sorted([{'peer_id':other,'agree':sum(x==y for x,y in zip(sig[mid],sig[other]))}
                     for other in active if other!=mid],key=lambda r:(-r['agree'],r['peer_id']))[:5]
         for mid in targets}
    return {'active_count':202,'collisions_25_25':collisions,
            'pairs_20_24':[r for r in pairs if 20<=r['agree']<=24],
            'statistical_top5_not_semantic_neighbors':top}


def pearson(a,b):
    x=[v for row in a for v in row]; y=[v for row in b for v in row]
    xm=sum(x)/len(x); ym=sum(y)/len(y)
    d=math.sqrt(sum((v-xm)**2 for v in x)*sum((v-ym)**2 for v in y))
    return sum((v-xm)*(w-ym) for v,w in zip(x,y))/d if d else None


