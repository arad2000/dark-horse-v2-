def apply(catalog,motives):
    planned={'majors_database_v2.json':catalog,'docs/data/micro_motives.json':motives,'micro_motives.json':motives}
    for path,wanted in planned.items():
        current=json.loads((ROOT/path).read_text())
        assert current==load_base(path) or current==wanted, f'Unexpected changes in {path}; refusing overwrite'
    for path,wanted in planned.items():
        p=ROOT/path
        if json.loads(p.read_text())!=wanted:p.write_text(json.dumps(wanted,ensure_ascii=False,indent=2)+'\n')


