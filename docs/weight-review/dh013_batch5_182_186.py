    old_rows=read_old_rows();new_rows={p['id']:p['strategies'] for p in proposals}
    rereads=[pair_reread(f,hypo,mm,new_rows,old_rows) for f in hscan if set(f['ids'])&set(IDS)]
    peers=[]
    for p in proposals:
        for pid in PEERS[p['id']]:
            pm=hypo[pid]
            peers.append({'id':p['id'],'peer':pid,'name':pm['name'],'active':pm['motive_driven'],
                          'agreement':sum(a==b for a,b in zip(sig(hypo[p['id']]),sig(pm))),
                          'pearson_informational':pearson(hypo[p['id']],pm),
                          'full_peer_texts':[{'code':c,'text':mm[c]['description_fa']} for c in pm['micro_motive_codes']]})
    bflags={tuple(f['ids']):f for f in before};aflags={tuple(f['ids']):f for f in after}
    delta={'added':[aflags[k] for k in sorted(aflags.keys()-bflags.keys())],
           'removed':[bflags[k] for k in sorted(bflags.keys()-aflags.keys())],
           'changed':[{'before':bflags[k],'after':aflags[k]} for k in sorted(bflags.keys()&aflags.keys()) if bflags[k]!=aflags[k]]}
    return {'audit_delta':delta,'base':BASE,'protocol_commit':PROTOCOL_COMMIT,'protocol_path':PROTOCOL_PATH,
            'protocol_sha256':hashlib.sha256(subprocess.check_output(['git','show',f'{PROTOCOL_COMMIT}:{PROTOCOL_PATH}'],cwd=ROOT)).hexdigest(),
            'ids':IDS,'skipped_inactive_ids':skipped,'major_count':len(majors),'active_count':202,
            'status':'DRAFT_REVIEW_NOT_MERGE_AUTHORIZED','independent_reviews_completed':False,
            'empirical_calibration_performed':False,'book_page_verification_performed':False,
            'proposals':proposals,'strategy_questions':qs['strategies']['questions'],
            'value_questions':qs['values']['questions'],'value_labels':poles,
            'baseline_scan':before,'runtime_scan':after,'hypothetical_scan':hscan,
            'high_agreement_rereads':rereads,'content_peer_checks':peers,
            'source_sha256':{path:hashlib.sha256((ROOT/path).read_bytes()).hexdigest() for path in ['docs/data/questions_v2.json','value_poles_v2.json']}},majors,motives

