def pair_reread(flag, byid, motives, new_rows, old_rows):
    pair=tuple(flag['ids']);sides=[];rows=[]
    assert pair in PAIR_NOTES, f'Unreviewed high-agreement pair: {pair}'
    for mid in pair:
        m=byid[mid]
        sides.append({'id':mid,'name':m['name'],'texts':[{'code':c,'text':motives[c]['description_fa']} for c in m['micro_motive_codes']]})
    for n in flag['questions']:
        entry={'question':n,'sides':[]}
        for side,mid in zip(sides,pair):
            weights=byid[mid]['strategy_weights'][n-1]
            evidence=new_rows.get(mid,old_rows.get(mid))
            if evidence is not None:
                r=evidence[n-1];assert r['weights']==weights
                ws=r['full_witnesses'];reason=r['reason'];status=r['status']
                for w in ws:assert motives[w['code']]['description_fa']==w['text']
            else:
                refs=OLD_CLUES.get(mid,{}).get(n,[])
                ws=[side['texts'][i-1] for i in refs]
                reason=('سرنخ محدود در متن قدیمی؛ انتقال به موقعیت دقیق این سؤال تأیید مستقل ندارد و منشأ وزن قدیمی معلوم نیست.' if refs else 'شاهد جهت‌دار همین سؤال در هفت متن قدیمی یافت نشد؛ برنده قدیمی توجیه جدید نمی‌شود؛ خارج دامنه تغییر است.')
                status='LEGACY_REREAD_NOT_REWEIGHTED'
            entry['sides'].append({'id':mid,'weights':weights,'full_witnesses':ws,'reason':reason,'status':status})
        rows.append(entry)
    oneflat=[n for n in flag['questions'] if sum(len(set(byid[mid]['strategy_weights'][n-1]))==1 for mid in pair)==1]
    return {**flag,'one_side_flat_agreements':oneflat,
            'directional_only_agreement':flag['agreement']-len(flag['flat_agreements'])-len(oneflat),
            'pearson_informational':pearson(byid[pair[0]],byid[pair[1]]),
            'explanation':PAIR_NOTES[pair],'both_sides':sides,'agreement_reread':rows}

