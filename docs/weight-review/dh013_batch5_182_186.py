def normalize(raw):
    out=[round(x/sum(raw),4) for x in raw]
    i=max(range(5), key=lambda j:raw[j])
    out[i]=round(out[i]+round(1-sum(out),4),4)
    return out

def parse_rows(text, n, size):
    out=[]
    for line in text.strip().splitlines():
        raw,refs,reason=line.split('|')
        equal=raw=='-'
        numbers=[int(x) for x in refs.split(',')] if refs!='-' else []
        weights=[.2]*5 if equal else list(map(float,raw.split()))
        if not equal: assert len(weights)==size
        out.append({'raw':None if equal else weights,'weights':normalize(weights) if size==5 else weights,
                    'motives':numbers,'reason':reason,'status':'EQUAL_NO_EVIDENCE' if equal else ('EXPERT_TRANSFER' if size==5 else 'INDEPENDENT_POLES')})
    assert len(out)==n
    return out

def sig(m):
    return tuple(max(range(5),key=lambda i:r[i]) for r in m['strategy_weights'])

def equal_count(rows):
    return sum(len(set(r['weights']))==1 for r in rows)

def permitted(rows):
    return equal_count(rows)<=6

def scan(majors):
    active=[m for m in majors if m.get('motive_driven')]
    assert len(active)==202
    flags=[]
    for a,b in itertools.combinations(active,2):
        agree=[i+1 for i,(x,y) in enumerate(zip(sig(a),sig(b))) if x==y]
        if len(agree)>=20:
            flats=[i for i in agree if len(set(a['strategy_weights'][i-1]))==1 and len(set(b['strategy_weights'][i-1]))==1]
            flags.append({'ids':[a['id'],b['id']], 'agreement':len(agree),'questions':agree,'flat_agreements':flats})
    return flags

