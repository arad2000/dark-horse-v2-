def parse(text,n,width,own):
    rows=h.parse_rows(text,n,width)
    for row in rows:
        row['full_witnesses']=[{'code':own[i-1]['code'],'text':own[i-1]['after']} for i in row['motives']]
    return rows

def build():
    before=baseline('majors_database_v2.json');majors=copy.deepcopy(before);by={m['id']:m for m in majors}
    motives=baseline('micro_motives.json');oldm={m['code']:copy.deepcopy(m) for m in motives};mm={m['code']:m for m in motives}
    chosen=[m['id'] for m in before if m['id']>186 and m['motive_driven']][:5];assert chosen==IDS
    skipped=[{'id':m['id'],'name':m['name']} for m in before if 186<m['id']<=IDS[-1] and not m['motive_driven']]
    proposals=[];hypo=copy.deepcopy(before);hypoby={m['id']:m for m in hypo}
    for mid in IDS:
        own=[]
        for c,t in zip(by[mid]['micro_motive_codes'],TEXTS[mid]):
            own.append({'code':c,'before':oldm[c]['description_fa'],'after':t,'provenance':'پیشنهاد نویسنده؛ موقعیت و لذت تألیفی، نه مشاهده میدانی یا نقل کتاب'})
            mm[c]['description_fa']=t
        assert len(own)==7
        sr=parse(S[mid],25,5,own);vr=parse(V[mid],15,2,own)
        value={f'Q{n}{a}':r['weights'][j] for n,r in enumerate(vr,1) for j,a in enumerate('AB')}
        eq=h.equal_count(sr);eligible=h.permitted(sr)
        sw=[r['weights'] for r in sr]
        hypoby[mid]['strategy_weights']=sw;hypoby[mid]['value_weights']=value
        if eligible:by[mid]['strategy_weights']=sw;by[mid]['value_weights']=value
        proposals.append({'id':mid,'name':by[mid]['name'],'texts':own,'strategies':sr,'values':vr,'value_weights':value,'equal':eq,'write_weights':eligible,'content_peers':PEERS[mid],'peer_reason':PEER_NOTES[mid]})
    p5=baseline('docs/weight-review/DH013_BATCH5_182_183_184_185_186.json')
    oldrows=h.read_old_rows()
    for p in p5['proposals']:oldrows[p['id']]=p['strategies']
    newrows={p['id']:p['strategies'] for p in proposals}
    scans={k:h.scan(v) for k,v in [('baseline',before),('runtime',majors),('hypothetical',hypo)]}
    for fs in scans.values():assert not any(f['agreement']==25 for f in fs),'25/25 collision requires evidence reread'
    rereads=[]
    # Both actual and hypothetical candidates must be identified; inherited
    # runtime weights are NOT retrospectively justified by our author proposals.
    for mode,source in [('runtime',majors),('hypothetical',hypo)]:
        sourceby={m['id']:m for m in source}
        for f in scans[mode]:
            if not set(f['ids'])&set(IDS):continue
            sides=[]
            for mid in f['ids']:
                sides.append({'id':mid,'name':sourceby[mid]['name'],'texts':[{'code':c,'text':mm[c]['description_fa']} for c in sourceby[mid]['micro_motive_codes']],'baseline_texts':[{'code':c,'text':oldm[c]['description_fa']} for c in sourceby[mid]['micro_motive_codes']] if mid in IDS else []})
            rows=[]
            for n in f['questions']:
                ss=[]
                for mid in f['ids']:
                    weights=sourceby[mid]['strategy_weights'][n-1]
                    candidate=(newrows.get(mid) if mode=='hypothetical' else None) or oldrows.get(mid)
                    if candidate is not None:
                        ev=copy.deepcopy(candidate[n-1]);assert ev['weights']==weights
                    else:
                        # Explicit gap rather than claiming these old weights
                        # were originally authored/validated from this text.
                        ev={'status':'LEGACY_ORIGIN_NOT_REVALIDATED','reason':'عدد قدیمی فقط برای اسکن است؛ منشأ وزن همین سؤال تأیید نشده. هفت متن کامل بالا برای بازخوانی‌اند، نه توجیه پسینی عدد.','full_witnesses':[]}
                    ss.append({'id':mid,'weights':weights,**ev})
                rows.append({'question':n,'sides':ss})
            oneflat=[r['question'] for r in rows if sum(len(set(s['weights']))==1 for s in r['sides'])==1]
            rereads.append({**f,'mode':mode,'both_sides':sides,'one_side_flat':oneflat,'directional_only':f['agreement']-len(f['flat_agreements'])-len(oneflat),'rows':rows,'pearson_informational':h.pearson(sourceby[f['ids'][0]],sourceby[f['ids'][1]]),'explanation':PAIR_NOTES.get(tuple(f['ids']),'بازخوانی ماهیتی این جفت هنوز باید تکمیل شود؛ به معنای رفع پرچم نیست.')})
    peer_checks=[]
    for p in proposals:
        for mid in p['content_peers']:
            m=by[mid];peer_checks.append({'id':p['id'],'peer':mid,'name':m['name'],'active':m['motive_driven'],'full_texts':[{'code':c,'text':mm[c]['description_fa']} for c in m['micro_motive_codes']],'reason':p['peer_reason']})
    questions=json.loads((ROOT/'docs/data/questions_v2.json').read_text())['layers']
    return {'base_commit':BASE,'value_poles':json.loads((ROOT/'value_poles_v2.json').read_text()),'source_sha256':{name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in ['docs/data/questions_v2.json','value_poles_v2.json']},'protocol_commit':'a1cdab9cd875bf9e9e01c19debf1e1237f58302b','ids':IDS,'skipped_inactive':skipped,'proposals':proposals,'peer_checks':peer_checks,'strategy_questions':questions['strategies']['questions'],'value_questions':questions['values']['questions'],'scans':scans,'rereads':rereads,'empirical_calibration_performed':False,'independent_review_performed':False,'merged_new_major_count_before_batch':25,'new_runtime_weights_in_this_draft':sum(p['write_weights'] for p in proposals)},majors,motives

