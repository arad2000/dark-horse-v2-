def parse(text):
    return [(list(map(float, a.split())), b.split(',') if b != '-' else [], c)
            for a, b, c in (line.split('|') for line in text.strip().splitlines())]


S = {mid: parse(text) for mid, text in S_TEXT.items()}
V = {mid: parse(text) for mid, text in V_TEXT.items()}


def proposals():
    return {mid: {'strategy_weights': [row for row, _, _ in S[mid]],
                  'value_weights': {f'Q{i}{side}': row[j] for i, (row, _, _) in enumerate(V[mid], 1)
                                    for j, side in enumerate('AB')}} for mid in S}


def baseline(path):
    return subprocess.check_output(['git', 'show', BASE + ':' + path], cwd=ROOT)


def signature(rows):
    return tuple(row.index(max(row)) for row in rows)


def validate(catalog):
    active = {m['id']: m for m in catalog if m.get('motive_driven') is not False}
    assert len(active) == 202
    scores = {mid: signature(m['strategy_weights']) for mid, m in active.items()}
    collisions = [(a, b) for a, b in itertools.combinations(scores, 2) if scores[a] == scores[b]]
    suspicious = [(a, b, sum(x == y for x, y in zip(scores[a], scores[b])))
                  for a, b in itertools.combinations(scores, 2) if a in S or b in S]
    suspicious = [x for x in suspicious if 20 <= x[2] < 25]
    assert not collisions, collisions
    return active, scores, suspicious


def build():
    catalog = json.loads(baseline('majors_database_v2.json'))
    original = {m['id']: m for m in catalog}
    motives = {m['code']: m for m in json.loads(baseline('docs/data/micro_motives.json'))}
    questions = json.loads(baseline('docs/data/questions_v2.json'))['layers']
    poles = json.loads(baseline('value_poles_v2.json'))
    candidate = json.loads(json.dumps(catalog))
    patches = proposals()
    result = {}
    for mid in S:
        codes = original[mid]['micro_motive_codes']
        assert len(set(codes)) == 7
        suffixes = {code.rsplit('-', 1)[1] for code in codes}
        assert len(S[mid]) == 25 and len(V[mid]) == 15
        for rows, width in ((S[mid], 5), (V[mid], 2)):
            for row, refs, reason in rows:
                assert len(row) == width and all(0 <= n <= 1 for n in row)
                assert set(refs) <= suffixes and reason
                if width == 5:
                    assert sum(Decimal(str(n)) for n in row) == 1
                    if len(set(row)) != 1:
                        assert refs, (mid, 'slope without evidence')
                elif row[0] != row[1]:
                    assert refs, (mid, 'value slope without evidence')
        equal = [i for i, (row, _, _) in enumerate(S[mid], 1) if len(set(row)) == 1]
        assert len(equal) <= 6, (mid, 'insufficient evidence: must not write this major')
        next(m for m in candidate if m['id'] == mid).update(patches[mid])
        active, scores, suspicious = validate(candidate)
        introduced = {k for k in S if k <= mid}
        introduced_suspicious = [x for x in suspicious if x[0] in introduced or x[1] in introduced]
        assert not introduced_suspicious, introduced_suspicious
        result[mid] = {'equal': equal, 'sequential_active': len(active)}
    active, scores, suspicious = validate(candidate)
    assert not suspicious, suspicious
    for mid in S:
        result[mid]['neighbors'] = sorted(
            [(other, sum(a == b for a, b in zip(scores[mid], sig))) for other, sig in scores.items() if other != mid],
            key=lambda x: (-x[1], x[0]))[:5]
    # Verify only two fields of exactly five majors would change.
    changed = [m['id'] for m in candidate if m != original[m['id']]]
    assert changed == list(range(161, 166))
    for m in candidate:
        if m['id'] not in S:
            assert m == original[m['id']]
        else:
            assert {k:v for k,v in m.items() if k not in patches[m['id']]} == {
                k:v for k,v in original[m['id']].items() if k not in patches[m['id']]}
    return original, motives, questions, poles, patches, result


