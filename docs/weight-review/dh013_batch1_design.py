        old=original[m['id']]
        if m != old:
            changed.append(m['id'])
            assert m['id'] in patches
            assert {k for k in old if m[k] != old[k]} == {'strategy_weights','value_weights'}
            assert all(m[k] == value for k,value in patches[m['id']].items())
