window.DHQuote = {
  todayIndex: function () {
    const d = new Date();
    const key = d.getFullYear() * 1000 + d.getMonth() * 50 + d.getDate();
    return key % window.DH_QUOTES.length;
  },
  today: function () {
    return window.DH_QUOTES[this.todayIndex()];
  },
  /** ۳–۴ جمله نزدیک به هم برای یک کارت */
  todayBundle: function () {
    const start = this.todayIndex();
    const n = window.DH_QUOTES.length;
    return [0, 1, 2].map(i => window.DH_QUOTES[(start + i) % n]);
  }
};
